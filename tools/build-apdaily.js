#!/usr/bin/env node
/* Builds teacher/js/scheduler-apdaily.js (AP Daily videos for the built-in templates) and
   tools/ap-daily-library.json (the same videos as Theta Scheduler library items, for POST /api/library/batch)
   from tools/ap-daily-physics1.json. Run: node tools/build-apdaily.js */
'use strict';
const fs = require('fs');
const path = require('path');

const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'ap-daily-physics1.json'), 'utf8'));
const DEFAULT_MIN = 10; // AP Daily videos run about 7–12 minutes

const videos = src.videos.map(([topic, n, id, desc, eks, seconds]) => {
	const unit = topic.split('.')[0];
	return {
		id,
		topic,
		n,
		title: `AP Daily ${topic} Video ${n}`,
		desc,
		eks,
		minutes: seconds ? Math.max(1, Math.round(seconds / 60)) : DEFAULT_MIN,
		url: src.linkTemplate.replace('{id}', id).replace('{unit}', unit)
	};
});

// sanity: every video has EKs, ids unique
const ids = new Set();
for (const v of videos) {
	if (!v.eks.length) throw new Error('No EKs for ' + v.title);
	if (ids.has(v.id)) throw new Error('Duplicate id ' + v.id);
	ids.add(v.id);
}

const js = `/* Theta Scheduler: College Board AP Daily videos for AP Physics 1 (AP Classroom), each aligned to the
   Essential Knowledge it covers (a best guess from the video's description — review it).
   Generated by tools/build-apdaily.js from tools/ap-daily-physics1.json — edit those, not this.
   Built-in templates use these to put one video assignment the evening before each class meeting. */
'use strict';
(function () {
	const HT = (window.HT = window.HT || {});
	HT.schedulerAPDaily = ${JSON.stringify({ source: src.source, videos })};
	// AP Physics 1 seeds (the AP framework and the Waddell sequence) get the videos
	for (const seed of Object.values(HT.schedulerSeeds || {})) if (/physics-1|waddell/.test(seed.id)) seed.data.dailyVideos = HT.schedulerAPDaily.videos;
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'teacher', 'js', 'scheduler-apdaily.js'), js);

// Library items (one per video)
const ap1 = (() => {
	global.window = global;
	global.HT = {};
	require(path.join(__dirname, '..', 'teacher', 'js', 'scheduler-seed-ap1.js'));
	return HT.schedulerSeeds['ap-physics-1'].data.objectiveTrees[0].nodes;
})();
const topicName = new Map(ap1.filter((n) => /^\d+\.\d+$/.test(n.code)).map((n) => [n.code, n.text]));
const entries = videos.map((v) => ({
	title: v.title,
	course: { id: 'ap-physics-1', label: 'AP Physics 1' },
	type: { id: 'video', label: 'Video', color: '#9333ea' },
	interaction: { id: 'individual', label: 'Individual', color: '#6b7280' },
	assessment: 'none',
	expectedMin: v.minutes,
	inClass: false,
	spanMeetings: 0,
	objectiveCodes: v.eks,
	topicHint: `${v.topic} ${topicName.get(v.topic) || ''}`.trim(),
	links: [{ label: `${v.topic}: Daily Video ${v.n} (AP Classroom)`, url: v.url }],
	notes: v.desc + '\nAssign the evening before class. Students sign in to AP Classroom to watch.'
}));
for (const e of entries) for (const c of e.objectiveCodes) if (!ap1.some((n) => n.code === c)) throw new Error(`${e.title}: unknown code ${c}`);
// POST /api/library/batch wants { entries: [{ item }] }
fs.writeFileSync(path.join(__dirname, 'ap-daily-library.json'), JSON.stringify({ entries: entries.map((item) => ({ item })) }, null, 1));
console.log(`${videos.length} videos → teacher/js/scheduler-apdaily.js, tools/ap-daily-library.json`);
